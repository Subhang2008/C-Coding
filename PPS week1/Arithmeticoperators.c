// This program is to demonstrate arithmetic operators

#include <stdio.h>

int main(){

    printf("\n3 + 5 = %d",3 + 5);
    printf("\n2 - 7 = %d",2 - 7);
    printf("\n3 * 8 = %d",3 * 8);
    printf("\n3 / 5 = %d",3 / 5);
    printf("\n3 / 5 = %.2f",3 / 5.0);
    printf("\n10 %% 7 = %d",10 % 7);
    
    return 0;

}